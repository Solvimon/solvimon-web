#!/usr/bin/env node
/**
 * Writes `src/components/customer/CheckoutForm/addressFormats.data.ts` from Google's address
 * metadata (libaddressinput, the data Chrome autofill uses): per country, which of the address
 * fields the checkout has are used, which are required, and the postal code pattern.
 *
 * Run: node scripts/generate-address-formats.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const BASE_URL = 'https://chromium-i18n.appspot.com/ssl-address/data';
const OUTPUT = path.join(
    path.dirname(fileURLToPath(import.meta.url)),
    '../src/components/customer/CheckoutForm/addressFormats.data.ts',
);

// Street, city, state, postal code: the address fields the checkout form has.
const FIELD_CODES = ['A', 'C', 'S', 'Z'];

const fetchJson = async (url) => {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    return response.json();
};

const usedFields = (fmt) => FIELD_CODES.filter((code) => fmt.includes(`%${code}`)).join('');
const requiredFields = (require) => FIELD_CODES.filter((code) => require.includes(code)).join('');

const defaults = await fetchJson(`${BASE_URL}/ZZ`);
const { countries } = await fetchJson(BASE_URL);

const entries = [];
for (const country of countries.split('~')) {
    if (!/^[A-Z]{2}$/.test(country)) continue;

    const data = await fetchJson(`${BASE_URL}/${country}`);
    const fields = usedFields(data.fmt ?? defaults.fmt);
    // A field a country does not use cannot be required of it.
    const required = requiredFields(data.require ?? defaults.require)
        .split('')
        .filter((code) => fields.includes(code))
        .join('');

    let postalCode;
    if (data.zip && fields.includes('Z')) {
        new RegExp(`^(?:${data.zip})$`, 'i');
        postalCode = data.zip;
    }

    entries.push([country, { fields, required, ...(postalCode ? { postalCode } : {}) }]);
}

const lines = entries.map(
    ([country, format]) =>
        `    ${country}: ${JSON.stringify(format).replace(/"(\w+)":/g, '$1: ')},`,
);

await writeFile(
    OUTPUT,
    `// Generated by scripts/generate-address-formats.mjs from Google's libaddressinput metadata.
// Do not edit by hand; run the script again instead.
import type { AddressFormat } from './addressFormat';

export const DEFAULT_ADDRESS_FORMAT: AddressFormat = ${JSON.stringify({
        fields: usedFields(defaults.fmt),
        required: requiredFields(defaults.require),
    }).replace(/"(\w+)":/g, '$1: ')};

export const ADDRESS_FORMATS: Record<string, AddressFormat> = {
${lines.join('\n')}
};
`,
);

console.log(`Wrote ${entries.length} countries to ${path.relative(process.cwd(), OUTPUT)}`);
